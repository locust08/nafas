import { createRequire } from 'node:module';
import { writeFile } from 'node:fs/promises';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.NAFAS_PLAYWRIGHT_PATH || 'playwright');
const base = 'http://127.0.0.1:3001';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
const checks = {};

await page.goto(base);
const nav = page.locator('.desktop-nav');
const hrefs = await nav.locator('a').evaluateAll(links => [...new Set(links.map(link => link.getAttribute('href')))]);
checks.desktopNavRoutes = [];
for (const href of hrefs) {
  await page.goto(base);
  const item = nav.locator(`a[href="${href}"]`).first();
  if (!await item.isVisible()) await nav.locator(`details:has(a[href="${href}"]) summary`).click();
  await item.click();
  await page.waitForURL(url => url.pathname === href);
  checks.desktopNavRoutes.push({ href, reached: new URL(page.url()).pathname === href });
}
await page.goto(base);
await page.locator('.header-contact').click();
await page.waitForURL(url => url.pathname === '/hubungi-kami');
checks.desktopContact = new URL(page.url()).pathname === '/hubungi-kami';
await page.goto(`${base}/berita-media`);
await page.locator('main a[href^="/berita-media/"]').first().click();
await page.waitForURL(url => url.pathname === '/berita-media/pengiktirafan-kecemerlangan-operasi');
checks.articleDetail = new URL(page.url()).pathname === '/berita-media/pengiktirafan-kecemerlangan-operasi';
await page.goto(`${base}/hubungi-kami`);
await page.locator('button[type=submit]').click();
checks.requiredFormFields = await page.locator('form').evaluate(form => !form.checkValidity());
await page.locator('#nama').fill('Semakan QA');
await page.locator('#emel').fill('qa@example.com');
await page.locator('#negeri').selectOption({ label: 'Selangor' });
await page.locator('#jenis').selectOption({ label: 'Pertanyaan Produk' });
await page.locator('#pertanyaan').fill('Semakan borang tempatan tanpa menghantar e-mel.');
await page.locator('button[type=submit]').click();
checks.emailDraft = (await page.locator('.form-status a').getAttribute('href')).startsWith('mailto:info@nafas.com.my?subject=');
await page.goto(`${base}/hubungi-kami?produk=Urea%20Prill%20(UP)`);
checks.productPrefill = await page.locator('input[name="Produk"]').inputValue() === 'Urea Prill (UP)';
await page.setViewportSize({ width: 390, height: 844 });
await page.goto(base);
const menu = page.locator('.menu-toggle');
await menu.click();
checks.mobileMenuOpen = await menu.getAttribute('aria-expanded') === 'true';
await page.keyboard.press('Escape');
checks.mobileMenuEscape = await menu.getAttribute('aria-expanded') === 'false';
checks.mobileMenuFocus = await menu.evaluate(el => document.activeElement === el);
await menu.click();
await page.locator('.mobile-nav details').nth(1).locator('summary').click();
await page.locator('.mobile-nav a[href="/produk/baja-tunggal"]').click();
await page.waitForURL(url => url.pathname === '/produk/baja-tunggal');
checks.mobileSubmenuNavigation = new URL(page.url()).pathname === '/produk/baja-tunggal';
checks.mobileMenuClosedOnNavigate = await page.locator('#mobile-navigation').count() === 0;
await page.emulateMedia({ reducedMotion: 'reduce' });
await page.goto(base);
checks.reducedMotionVideo = await page.locator('video').evaluate(video => video.paused);
const links = await page.locator('a[href^="/"]').evaluateAll(items => [...new Set(items.map(item => item.getAttribute('href')))]);
checks.homeInternalLinks = [];
for (const href of links) {
  const response = await page.request.get(`${base}${href}`);
  checks.homeInternalLinks.push({ href, status: response.status() });
}
await writeFile('output/playwright/strict-qa/interactions.json', JSON.stringify({ checks, errors }, null, 2));
await browser.close();
console.log(JSON.stringify({ checks, errors }, null, 2));
if (errors.length || checks.desktopNavRoutes.some(item => !item.reached) || checks.homeInternalLinks.some(item => item.status !== 200) || Object.values(checks).some(value => !Array.isArray(value) && !value)) process.exitCode = 1;
